import dotenv from "dotenv";
dotenv.config();

import mongoose from "mongoose";
import { IUserData } from "./interfaces";
import { checkPassword, hashPassword, normalizeEmail } from "./auth/password";

const mongoURI = process.env.MONGO_URI;

if (!mongoURI) {
  console.error("❌ MONGO_URI is not defined");
  process.exit(1);
}

mongoose
  .connect(mongoURI, {})
  .then(() => console.log("✅ Connected to MongoDB"))
  .catch((err) => console.error("MongoDB connection error:", err));

// The user-service only keeps the profile and account information.
// Medications, diet data and the rest belong to the services that own them
// and are saved through the registration saga.
const userSchema = new mongoose.Schema({
  email: { type: String, required: true, unique: true },
  password: { type: String, required: true }, // bcrypt hash
  name: { type: String, required: true },
  age: { type: String, required: true },
  gender: {
    type: String,
    required: true,
    enum: ["Male", "Female"],
  },
  // PENDING: created by a registration saga that has not finished. Such a user cannot log in
  // and is invisible to every other endpoint. Users created before this field existed have no
  // status at all and count as ACTIVE (queries use `status: { $ne: "PENDING" }`).
  status: { type: String, enum: ["PENDING", "ACTIVE"], default: "ACTIVE" },
  registrationId: { type: String, index: true },
});

const User = mongoose.model("User", userSchema);

const notPending = { $ne: "PENDING" } as const;

/* ------------------------------------------------------------------------------------------ */
/* Registration saga: the local steps of the orchestrator                                      */
/* ------------------------------------------------------------------------------------------ */
export interface NewPendingUser {
  id: string; // 24 hex characters, generated by the saga so every service uses the same id
  registrationId: string;
  username: string;
  email: string;
  passwordHash: string;
  age: number;
  gender: "Male" | "Female";
}

export function isDuplicateKeyError(error: unknown): boolean {
  return (
    typeof error === "object" &&
    error !== null &&
    (error as { code?: number }).code === 11000
  );
}

/** Throws a duplicate-key error (code 11000) when the email is already taken. */
export async function createPendingUser(user: NewPendingUser): Promise<void> {
  await User.create({
    _id: user.id,
    registrationId: user.registrationId,
    name: user.username,
    email: normalizeEmail(user.email),
    password: user.passwordHash,
    age: String(user.age),
    gender: user.gender,
    status: "PENDING",
  });
}

/** Idempotent. */
export async function activateUser(userId: string): Promise<void> {
  await User.updateOne(
    { _id: userId, status: "PENDING" },
    { $set: { status: "ACTIVE" } },
  );
}

/** Compensation. Idempotent, and it can never delete an ACTIVE account. */
export async function deletePendingUser(userId: string): Promise<void> {
  await User.deleteOne({ _id: userId, status: "PENDING" });
}

/* ------------------------------------------------------------------------------------------ */
/* Other user operations                                                                       */
/* ------------------------------------------------------------------------------------------ */
export async function updateUser(
  userId: string,
  updatedData: IUserData & { password?: string },
) {
  try {
    const data = { ...updatedData };
    if (data.password) data.password = await hashPassword(data.password);

    const updatedUser = await User.findOneAndUpdate(
      { _id: userId, status: notPending },
      data,
      { new: true, runValidators: true },
    ).select("-password");
    if (updatedUser) {
      return updatedUser;
    }
  } catch (error) {
    console.error("Error updating user:", error);
  }
}

export async function getUserById(userId: string) {
  try {
    const user = await User.findOne({ _id: userId, status: notPending }).select(
      "-password",
    );
    if (user) {
      return user;
    } else {
      return null;
    }
  } catch (error) {
    console.error("Error retrieving user:", error);
  }
}

export async function deleteUserById(userId: string) {
  try {
    const deletedUser = await User.findOneAndDelete({
      _id: userId,
      status: notPending,
    });
    if (deletedUser) {
      return deletedUser;
    }
  } catch (error) {
    console.error("Error deleting user:", error);
  }
}

export async function verifyUserCredentials({
  email,
  password,
}: {
  email: string;
  password: string;
}) {
  try {
    const normalized = normalizeEmail(email);
    // accounts created before emails were lower-cased may still be stored as typed
    const user = await User.findOne({
      email: { $in: [normalized, email.trim()] },
      status: notPending,
    });
    if (!user) return null;

    const { ok, needsRehash } = await checkPassword(password, user.password);
    if (!ok) return null;

    if (needsRehash) {
      user.password = await hashPassword(password); // upgrade a legacy plain-text password
      await user.save();
    }
    return user;
  } catch (error) {
    console.error("Error verifying user credentials:", error);
    return null;
  }
}
