import { Request, Response, Router } from "express";
import { RegistrationView } from "../Kafka/contracts/registration";
import { RegistrationSaga } from "./registration.service";
import { parseRegistrationRequest } from "./validation";

const UUID =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

/** How long POST /register waits for the saga before answering "202, still working". */
const DEFAULT_WAIT_MS = Number(process.env.REGISTRATION_WAIT_MS ?? 8_000);

function respond(res: Response, view: RegistrationView): void {
  if (view.status === "COMPLETED") {
    res.status(201).json(view);
  } else if (view.status === "FAILED") {
    // an email that is already registered is a conflict; anything else could not be processed
    res.status(view.code === "EMAIL_TAKEN" ? 409 : 422).json(view);
  } else {
    res.status(202).json(view); // the client polls GET /register/:registrationId
  }
}

export function createRegistrationRouter(
  saga: RegistrationSaga,
  options: { waitMs?: number } = {},
): Router {
  const router = Router();
  const waitMs = options.waitMs ?? DEFAULT_WAIT_MS;

  // POST /register     header: Idempotency-Key: <uuid generated by the app>
  //   201 { status: "COMPLETED", userId }   everything saved
  //   202 { status: "PENDING" }             still working: poll GET /register/:id
  //   409 / 422 { status: "FAILED", error, code }   nothing was saved anywhere
  router.post(
    "/register",
    async (req: Request, res: Response): Promise<void> => {
      const key = req.header("Idempotency-Key");
      if (!key || !UUID.test(key)) {
        res
          .status(400)
          .json({ error: "An Idempotency-Key header with a UUID is required" });
        return;
      }
      const request = parseRegistrationRequest(req.body);
      if (typeof request === "string") {
        res.status(400).json({ error: request });
        return;
      }

      const registrationId = key.toLowerCase();
      try {
        let view = await saga.start(registrationId, request);
        if (view.status === "PENDING")
          view = (await saga.waitForOutcome(registrationId, waitMs)) ?? view;
        respond(res, view);
      } catch (error) {
        console.error("Registration failed to start:", error);
        res.status(500).json({
          error: "Registration could not be started, please try again",
        });
      }
    },
  );

  // GET /register/:registrationId  ->  { status: "PENDING" | "COMPLETED" | "FAILED", ... }
  router.get(
    "/register/:registrationId",
    async (req: Request, res: Response): Promise<void> => {
      try {
        const view = await saga.getView(
          String(req.params.registrationId).toLowerCase(),
        );
        if (!view) {
          res.status(404).json({ error: "Unknown registration" });
          return;
        }
        res.status(200).json(view);
      } catch (error) {
        console.error("Could not read the registration:", error);
        res.status(500).json({ error: "Could not read the registration" });
      }
    },
  );

  return router;
}
